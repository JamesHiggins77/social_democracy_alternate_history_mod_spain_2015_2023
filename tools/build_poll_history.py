#!/usr/bin/env python3
"""Build out/html/spain/poll_history_data.js: a monthly poll of polls for
December 2011 - November 2015, from the opinion polls listed on English
Wikipedia's "Opinion polling for the 2015 Spanish general election"
(CC BY-SA; the underlying figures are the pollsters' published results).

Usage:
    curl -G https://en.wikipedia.org/w/api.php --data-urlencode action=parse \
      --data-urlencode "page=Opinion polling for the 2015 Spanish general election" \
      --data-urlencode prop=text --data-urlencode format=json \
      --data-urlencode formatversion=2 -o op2015.json
    python3 tools/build_poll_history.py op2015.json

Each month's value is the mean of all polls whose fieldwork ended that
month, then smoothed with a centred three-month average. Requires bs4.
"""
import json
import re
import sys
from pathlib import Path

from bs4 import BeautifulSoup

COLUMNS = {"PP": "pp", "PSOE": "psoe", "IU–UPeC": "iu", "IU–LV": "iu", "UPYD": "upyd", "UPyD": "upyd",
           "C's": "cs", "Podemos": "up"}
MONTHS = {m: i + 1 for i, m in enumerate(
    ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"])}
TABLE_YEARS = [2015, 2014, 2013, 2012]
FIRST, LAST = (2011, 12), (2015, 11)


def end_month(text, year):
    months = re.findall(r"(Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)", text)
    if not months:
        return None
    return year, MONTHS[months[-1]]


def first_number(text):
    m = re.match(r"\s*(\d+(?:\.\d+)?)", text)
    return float(m.group(1)) if m else None


def main(path):
    html = json.load(open(path))["parse"]["text"]
    soup = BeautifulSoup(html, "html.parser")
    tables = soup.find_all("table", class_="wikitable")[:4]
    polls = []
    for table, year in zip(tables, TABLE_YEARS):
        header = table.find("tr").find_all(["th", "td"])
        names = []
        for c in header:
            a = c.find("a")
            names.append(c.get_text(" ", strip=True) or (a.get("title") if a else ""))
        for row in table.find_all("tr")[1:]:
            cells = row.find_all(["td", "th"])
            if len(cells) < len(names) - 1:
                continue
            firm = cells[0].get_text(" ", strip=True)
            if "election" in firm.lower():
                continue
            when = end_month(cells[1].get_text(" ", strip=True), year)
            if not when:
                continue
            values = {}
            for name, cell in zip(names, cells):
                pid = COLUMNS.get(name)
                if pid:
                    v = first_number(cell.get_text(" ", strip=True))
                    if v is not None:
                        values[pid] = v
            if "pp" in values and "psoe" in values:
                polls.append((when, values))
    # monthly means
    months = []
    y, m = FIRST
    while (y, m) <= LAST:
        months.append((y, m))
        y, m = (y + (m == 12), m % 12 + 1)
    raw = {}
    for (ym, values) in polls:
        if ym < FIRST or ym > LAST:
            continue
        for pid, v in values.items():
            raw.setdefault(ym, {}).setdefault(pid, []).append(v)
    parties = sorted(set(COLUMNS.values()))
    monthly = []
    for ym in months:
        row = {}
        for pid in parties:
            vals = raw.get(ym, {}).get(pid)
            row[pid] = sum(vals) / len(vals) if vals else None
        monthly.append(row)
    # centred three-month smoothing; gaps filled from neighbours
    out = []
    for i, ym in enumerate(months):
        point = {"date": f"{ym[0]}-{ym[1]:02d}"}
        for pid in parties:
            window = [monthly[j][pid] for j in range(max(0, i - 1), min(len(months), i + 2))
                      if monthly[j][pid] is not None]
            if window:
                point[pid] = round(sum(window) / len(window), 1)
        out.append(point)
    target = Path(__file__).resolve().parent.parent / "out" / "html" / "spain" / "poll_history_data.js"
    target.write_text(
        "// Generated by tools/build_poll_history.py from the polls listed on English Wikipedia,\n"
        "// \"Opinion polling for the 2015 Spanish general election\" (CC BY-SA). Do not edit.\n"
        "(function (root) {\n  var DATA = " + json.dumps(out, separators=(",", ":")) + ";\n"
        "  if (typeof module !== 'undefined' && module.exports) { module.exports = DATA; }\n"
        "  else { root.SPAIN_POLL_HISTORY = DATA; }\n})(this);\n", encoding="utf-8")
    print(f"{len(polls)} polls -> {len(out)} months; first {out[0]}; last {out[-1]}")


if __name__ == "__main__":
    main(sys.argv[1])
