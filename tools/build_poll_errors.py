#!/usr/bin/env python3
"""Measure how wrong Spain's final polls were, 2015-2023, and write
out/html/spain/poll_error_data.js for the game's polling error model.

Sources: the opinion-poll lists on English Wikipedia (CC BY-SA), one page per
general election, fetched as in tools/build_poll_history.py:
    op2015.json, op2016.json, op2019a.json, op2019n.json, op2023.json

For each election: the mean of all polls whose fieldwork ended in the last
21 days (exit polls excluded) minus the result shown on the same page
(both as % of valid votes). Positive = the polls overestimated the party.

Usage: python3 tools/build_poll_errors.py DIR_WITH_JSON
"""
import datetime as dt
import json
import re
import statistics
import sys
from pathlib import Path

from bs4 import BeautifulSoup

ELECTIONS = {
    "2015": ("op2015.json", dt.date(2015, 12, 20)),
    "2016": ("op2016.json", dt.date(2016, 6, 26)),
    "2019a": ("op2019a.json", dt.date(2019, 4, 28)),
    "2019n": ("op2019n.json", dt.date(2019, 11, 10)),
    "2023": ("op2023.json", dt.date(2023, 7, 23)),
}
COLUMNS = {
    "PP": "pp", "PSOE": "psoe", "C's": "cs", "Cs": "cs", "Vox": "vox",
    "Podemos": "up", "Unidos Podemos": "up", "Unidas Podemos": "up", "UP": "up", "Sumar": "up",
    "Más País": "mp", "IU–UPeC": "iu",
}
MONTHS = {m: i + 1 for i, m in enumerate(
    ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"])}


def end_date(text, year):
    found = re.findall(r"(\d{1,2})\s*(Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)", text)
    if not found:
        return None
    day, mon = found[-1]
    return dt.date(year, MONTHS[mon], int(day))


def number(text):
    m = re.match(r"\s*(\d+(?:\.\d+)?)", text)
    return float(m.group(1)) if m else None


def header_names(table):
    names = []
    for c in table.find("tr").find_all(["th", "td"]):
        a = c.find("a")
        text = c.get_text(" ", strip=True)
        title = a.get("title", "") if a else ""
        name = text or title
        # logo headers link to party articles; map article titles to short names
        for key, short in [("People's Party", "PP"), ("Spanish Socialist", "PSOE"), ("Citizens", "C's"),
                           ("Vox", "Vox"), ("Sumar", "Sumar"), ("Unidas Podemos", "Unidas Podemos"),
                           ("Unidos Podemos", "Unidos Podemos"), ("Podemos", "Podemos"), ("Más País", "Más País")]:
            if not text and key in title:
                name = short
                break
        names.append(name)
    return names


def analyse(path, date):
    html = json.load(open(path))["parse"]["text"]
    table = BeautifulSoup(html, "html.parser").find_all("table", class_="wikitable")[0]
    names = header_names(table)
    result, polls = None, []
    for row in table.find_all("tr")[1:]:
        cells = row.find_all(["td", "th"])
        if len(cells) < 6:
            continue
        firm = cells[0].get_text(" ", strip=True)
        values = {}
        for name, cell in zip(names, cells):
            pid = COLUMNS.get(name)
            if pid and pid not in values:
                v = number(cell.get_text(" ", strip=True))
                if v is not None:
                    values[pid] = v
        if "election" in firm.lower():
            if result is None and "pp" in values:
                result = values
            continue
        if "exit" in firm.lower():
            continue
        end = end_date(cells[1].get_text(" ", strip=True), date.year)
        if end and 0 <= (date - end).days <= 21 and "pp" in values:
            polls.append(values)
    errors = {}
    for pid, res in result.items():
        vals = [p[pid] for p in polls if pid in p]
        if len(vals) >= 3:
            errors[pid] = round(statistics.mean(vals) - res, 2)
    return {"polls": len(polls), "result": result, "errors": errors}


def main(folder):
    out = {"elections": {}, "parties": {}}
    for key, (f, date) in ELECTIONS.items():
        a = analyse(Path(folder) / f, date)
        out["elections"][key] = a
        print(key, a["polls"], "polls; errors (poll - result):", a["errors"])
    parties = sorted({p for e in out["elections"].values() for p in e["errors"]})
    for p in parties:
        errs = [e["errors"][p] for e in out["elections"].values() if p in e["errors"]]
        out["parties"][p] = {
            "bias": round(statistics.mean(errs), 2),
            "sd": round(statistics.pstdev(errs), 2) if len(errs) > 1 else 1.5,
            "n": len(errs),
        }
        print(f"  {p}: mean error {out['parties'][p]['bias']:+.2f}, sd {out['parties'][p]['sd']:.2f} over {len(errs)}")
    target = Path(__file__).resolve().parent.parent / "out" / "html" / "spain" / "poll_error_data.js"
    target.write_text(
        "// Generated by tools/build_poll_errors.py from the poll lists on English Wikipedia (CC BY-SA).\n"
        "(function (root) {\n  var DATA = " + json.dumps(out, separators=(",", ":")) + ";\n"
        "  if (typeof module !== 'undefined' && module.exports) { module.exports = DATA; }\n"
        "  else { root.SPAIN_POLL_ERRORS = DATA; }\n})(this);\n", encoding="utf-8")
    print("wrote", target)


if __name__ == "__main__":
    main(sys.argv[1])
