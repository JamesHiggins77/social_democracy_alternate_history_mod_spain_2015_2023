#!/usr/bin/env python3
"""Build out/html/spain/map_data.js: simplified SVG paths for Spain's provinces.

Source: Natural Earth 1:10m admin-1 states and provinces (public domain),
https://www.naturalearthdata.com/  (ne_10m_admin_1_states_provinces).

Usage:
    python3 tools/build_map.py path/to/ne_10m_admin_1_states_provinces.shp

The Canary Islands are moved into an inset at the bottom left. Requires
pyshp and shapely (pip install pyshp shapely).
"""
import json
import math
import sys
from pathlib import Path

import shapefile
from shapely.geometry import shape
from shapely.ops import transform, unary_union

RENAME = {
    "La Coruña": "A Coruña", "Álava": "Araba", "Gerona": "Girona", "Lérida": "Lleida",
    "Orense": "Ourense", "Santa Cruz de Tenerife": "SC de Tenerife",
}
CANARIES = {"Las Palmas", "SC de Tenerife"}
WIDTH = 600.0
LAT0 = 40.0  # standard parallel for the equirectangular projection


def main(shp):
    r = shapefile.Reader(str(Path(shp).with_suffix("")))
    names = [f[0] for f in r.fields[1:]]
    shapes = {}
    for sr in r.shapeRecords():
        rec = dict(zip(names, sr.record))
        if rec["iso_a2"] != "ES":
            continue
        name = RENAME.get(rec["name"], rec["name"])
        shapes[name] = shape(sr.shape.__geo_interface__)

    kx = math.cos(math.radians(LAT0))

    def project(geom, dx=0.0, dy=0.0):
        return transform(lambda x, y, z=None: ((x + dx) * kx, -(y + dy)), geom)

    # Canaries: shift north-east into an inset below Andalusia
    projected = {}
    for name, g in shapes.items():
        if name in CANARIES:
            g = project(g, dx=4.5, dy=7.5)
        else:
            g = project(g)
        projected[name] = g.simplify(0.02, preserve_topology=True)

    minx = min(g.bounds[0] for g in projected.values())
    miny = min(g.bounds[1] for g in projected.values())
    maxx = max(g.bounds[2] for g in projected.values())
    maxy = max(g.bounds[3] for g in projected.values())
    scale = WIDTH / (maxx - minx)
    height = (maxy - miny) * scale

    def path(geom):
        polys = list(geom.geoms) if geom.geom_type == "MultiPolygon" else [geom]
        out = []
        for p in polys:
            for ring in [p.exterior] + list(p.interiors):
                pts = [((x - minx) * scale, (y - miny) * scale) for x, y in ring.coords]
                if len(pts) < 4:
                    continue
                out.append("M" + "L".join(f"{x:.1f},{y:.1f}" for x, y in pts) + "Z")
        return "".join(out)

    # autonomous communities: provinces merged, for bold outlines
    elections_js = (Path(__file__).resolve().parent.parent / "out" / "html" / "spain" / "election_data.js").read_text(encoding="utf-8")
    regions = json.loads(elections_js[elections_js.index("var DATA = ") + 11:elections_js.rindex(";\n  if")])["regions"]
    region_paths = {}
    for region, provs in regions.items():
        merged = unary_union([projected[p].buffer(0.01) for p in provs]).buffer(-0.01)
        region_paths[region] = path(merged.simplify(0.02, preserve_topology=True))

    data = {
        "source": "Natural Earth 1:10m admin-1 (public domain)",
        "regions": region_paths,
        "width": round(WIDTH), "height": round(height),
        "canariesBox": None,
        "provinces": {n: path(g) for n, g in sorted(projected.items())},
    }
    xs = [projected[n].bounds for n in CANARIES]
    data["canariesBox"] = [round((min(b[0] for b in xs) - minx) * scale - 6), round((min(b[1] for b in xs) - miny) * scale - 6),
                           round((max(b[2] for b in xs) - min(b[0] for b in xs)) * scale + 12),
                           round((max(b[3] for b in xs) - min(b[1] for b in xs)) * scale + 12)]
    target = Path(__file__).resolve().parent.parent / "out" / "html" / "spain" / "map_data.js"
    target.write_text(
        "// Generated by tools/build_map.py from Natural Earth (public domain) - do not edit.\n"
        "(function (root) {\n  var DATA = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n"
        "  if (typeof module !== 'undefined' && module.exports) { module.exports = DATA; }\n"
        "  else { root.SPAIN_MAP = DATA; }\n})(this);\n", encoding="utf-8")
    print(f"wrote {target} ({target.stat().st_size // 1024} KiB), {len(data['provinces'])} provinces, "
          f"{data['width']}x{data['height']}")


if __name__ == "__main__":
    main(sys.argv[1])
