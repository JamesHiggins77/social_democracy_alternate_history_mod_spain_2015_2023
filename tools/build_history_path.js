#!/usr/bin/env node
// Build out/html/spain/history_path_data.js: the "historical currents" of
// July 2014 - November 2015 - the rise and fall of Podemos and Ciudadanos,
// the PP's erosion, the collapse of IU and UPyD.
//
// For each month, national factors are fitted so that the polls the player
// sees - the vote model with the December 2015 polling error applied
// (poll_error_data.js) - equal the real poll average for that month
// (poll_history_data.js). The path's factor is that fit divided by the
// polling error, so the true vote is the polls minus the error, and the path
// ends at the real December 2015 result (factor 1).
//
// Usage: node tools/build_history_path.js
'use strict';
const fs = require('fs');
const path = require('path');
const V = require('../out/html/spain/vote_model.js');
const DATA = require('../out/html/spain/election_data.js');
const HIST = require('../out/html/spain/poll_history_data.js');
const ERR = require('../out/html/spain/poll_error_data.js');

const PARTIES = ['pp', 'psoe', 'up', 'cs', 'iu', 'upyd'];
const e2015 = ERR.elections['2015'];
const rel = {};
for (const p of PARTIES) {
  rel[p] = e2015.result[p] && e2015.errors[p] !== undefined ? e2015.errors[p] / e2015.result[p] : 0;
}
const base = V.buildBaseline(DATA, V.initialState());
const out = {};
for (const row of HIST.filter(r => r.date >= '2014-07' && r.date <= '2015-11')) {
  const target = {};
  for (const p of PARTIES) {
    if (row[p] !== undefined) target[p] = Math.max(0.5, row[p]);
  }
  const s = V.initialState();
  s.partyFactor = {};
  for (const p of PARTIES) s.partyFactor[p] = 1;
  const [y, m] = row.date.split('-').map(Number);
  for (let it = 0; it < 40; it++) {
    const shares = V.runGeneralElection(s, base, DATA, y, m).voteShares;
    for (const p of Object.keys(target)) {
      const cur = Math.max(0.05, shares[p] || 0);
      s.partyFactor[p] *= Math.pow(target[p] / cur, 0.8);
    }
  }
  const fit = V.runGeneralElection(s, base, DATA, y, m).voteShares;
  out[row.date] = {};
  for (const p of PARTIES) out[row.date][p] = Math.round(s.partyFactor[p] / (1 + rel[p]) * 1000) / 1000;
  console.log(row.date, PARTIES.map(p => `${p} ${(fit[p] || 0).toFixed(1)}/${(target[p] || 0).toFixed(1)}`).join('  '));
}
const target = path.join(__dirname, '..', 'out', 'html', 'spain', 'history_path_data.js');
fs.writeFileSync(target,
  '// Generated by tools/build_history_path.js - do not edit by hand.\n' +
  '(function (root) {\n  var DATA = ' + JSON.stringify(out) + ';\n' +
  "  if (typeof module !== 'undefined' && module.exports) { module.exports = DATA; }\n" +
  '  else { root.SPAIN_HISTORY_PATH = DATA; }\n})(this);\n');
console.log('wrote', target);
