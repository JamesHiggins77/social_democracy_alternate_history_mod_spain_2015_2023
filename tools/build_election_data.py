#!/usr/bin/env python3
"""Build out/html/spain/election_data.js from official general-election results.

Source data: Spanish Ministry of the Interior (infoelectoral) results, as
compiled in https://github.com/josemam/MiCongreso (data.json).  Only the
numbers are extracted; no code from that project is used.

Usage:
    git clone --depth 1 https://github.com/josemam/MiCongreso /tmp/MiCongreso
    python3 tools/build_election_data.py /tmp/MiCongreso/data.json

The output keeps every candidacy separate, exactly as it appeared on the
ballot in each province, and adds a mapping from ballot labels to the game's
party ids.  Labels not in PARTY_MAP keep their own id ("x:" + label) so that
unrelated small lists are never merged into one candidacy.
"""
import json
import sys
from pathlib import Path

SOURCE_URL = "https://github.com/josemam/MiCongreso"
SOURCE_COMMIT = "fd5dbbd38dba751d218e91993237956fec19cc56"

ELECTIONS = [
    # (game key, source key, polling date)
    ("2011", "espana_2011", "2011-11-20"),
    ("2015", "espana_2015", "2015-12-20"),
    ("2016", "espana_2016", "2016-06-26"),
    ("2019a", "espana_2019_abril", "2019-04-28"),
    ("2019n", "espana_2019_noviembre", "2019-11-10"),
    ("2023", "espana_2023", "2023-07-23"),
]

# Ballot label -> game party id.  Confluences and alliances map onto the
# political space they belong to in the simulation.
PARTY_MAP = {
    # People's Party
    "PP": "pp",
    # PSOE (the PSC appears on the ballot as PSOE in this data set)
    "PSOE": "psoe",
    # Ciudadanos
    "C's": "cs", "Cs": "cs",
    # Vox
    "VOX": "vox",
    # Podemos and its confluences; later Unidas Podemos and Sumar
    "PODEMOS": "up", "EN COMÚ": "up", "PODEMOS-COM": "up", "PODEMOS-En": "up",
    "PODEMOS-IU-EQUO": "up", "ECP": "up", "PODEMOS-COMPROMÍS-EUPV": "up",
    "PODEMOS-EN MAREA-ANOVA-EU": "up", "ECP-GUANYEM EL CANVI": "up",
    "PODEMOS-EU-MAREAS EN COMÚN-EQUO": "up", "PODEMOS-IU": "up",
    "PODEMOS-EU": "up", "SUMAR": "up",
    # Izquierda Unida when it stood separately (2015)
    "IU-UPeC": "iu",
    # Más País / Compromís when standing apart from Podemos
    "COMPROMÍS 2019": "mp", "MÁS PAÍS-EQUO": "mp", "MÁS PAÍS": "mp",
    "MÉS COMPROMÍS": "mp", "M PAÍS-CHA-EQUO": "mp",
    # Catalonia
    "ERC-CATSI": "erc", "ERC-CATSÍ": "erc", "ERC-SOBIRANISTES": "erc", "ERC": "erc",
    "DL": "junts", "CDC": "junts", "JxCAT-JUNTS": "junts", "JxCAT - JUNTS": "junts",
    "CUP-PR": "cup",
    # Basque Country and Navarre
    "EAJ-PNV": "pnv",
    "EH Bildu": "bildu",
    "NA+": "upn", "U.P.N.": "upn",
    "GBAI": "geroa",
    # Galicia
    "NÓS": "bng", "BNG-NÓS": "bng", "BNG": "bng", "B.N.G.": "bng",
    # Canary Islands
    "CCa-PNC": "cc", "CCa-PNC-NC": "cc", "CCa": "cc",
    "Nca": "nc", "NC-bc": "nc",
    # Cantabria
    "PRC": "prc",
    # Empty Spain platforms
    "¡TERUEL EXISTE!": "te", "EXISTE": "te",
    # 2011 labels
    "IU-LV": "iu", "AMAIUR": "bildu", "CiU": "junts", "ESQUERRA": "erc",
    "COMPROMÍS-Q": "mp", "CC-NC-PNC": "cc", "FAC": "foro", "P.R.C.": "prc",
    # Minor statewide lists
    "PACMA": "pacma", "UPYD": "upyd", "UPyD": "upyd",
}


def party_id(label):
    return PARTY_MAP.get(label, "x:" + label)


def main(path):
    src = json.loads(Path(path).read_text(encoding="utf-8"))
    out = {
        "source": {
            "description": "Official results, Spanish Ministry of the Interior (infoelectoral), "
                           "via the MiCongreso data set",
            "url": SOURCE_URL,
            "commit": SOURCE_COMMIT,
        },
        "regions": None,
        "provinceRegion": {},
        "elections": {},
    }
    regions = src["espana_2015"]["circunscripciones"]
    out["regions"] = regions
    for region, provinces in regions.items():
        for prov in provinces:
            out["provinceRegion"][prov] = region

    for key, src_key, date in ELECTIONS:
        e = src[src_key]
        assert e["circunscripciones"] == regions, f"region layout changed in {key}"
        provinces = {}
        for prov, res in sorted(e["resultados"].items()):
            lists = []
            seen = {}
            for label, votes in sorted(res.items(), key=lambda kv: -kv[1]):
                pid = party_id(label)
                assert pid not in seen, f"{key} {prov}: {label} and {seen.get(pid)} both map to {pid}"
                seen[pid] = label
                lists.append([pid, label, votes])
            provinces[prov] = {
                "population": e["ultimo_censo"][prov],
                "blank": e["blancos"][prov],
                "null": e["nulos"][prov],
                "lists": lists,
            }
        out["elections"][key] = {"date": date, "provinces": provinces}

    target = Path(__file__).resolve().parent.parent / "out" / "html" / "spain" / "election_data.js"
    target.parent.mkdir(parents=True, exist_ok=True)
    body = json.dumps(out, ensure_ascii=False, separators=(",", ":"))
    target.write_text(
        "// Generated by tools/build_election_data.py - do not edit by hand.\n"
        "(function (root) {\n"
        "  var DATA = " + body + ";\n"
        "  if (typeof module !== 'undefined' && module.exports) { module.exports = DATA; }\n"
        "  else { root.SPAIN_ELECTION_DATA = DATA; }\n"
        "})(this);\n",
        encoding="utf-8",
    )
    print(f"wrote {target} ({target.stat().st_size // 1024} KiB)")


if __name__ == "__main__":
    main(sys.argv[1])
